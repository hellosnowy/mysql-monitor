func TestSessionWrapping(t *testing.T) {
	e := &Emitter{}

	if got := e.SessionBegin(); !reflect.DeepEqual(got, []string{"BEGIN;"}) {
		t.Fatalf("SessionBegin got %#v", got)
	}
	if got := e.SessionEnd(); !reflect.DeepEqual(got, []string{"COMMIT;"}) {
		t.Fatalf("SessionEnd got %#v", got)
	}
	for name, got := range map[string][]string{
		"DDLBegin":      e.DDLBegin(),
		"DDLEnd":        e.DDLEnd(),
		"DMLBegin":      e.DMLBegin(),
		"DMLEnd":        e.DMLEnd(),
		"TableDMLBegin": e.TableDMLBegin(nil, true),
		"TableDMLEnd":   e.TableDMLEnd(nil, true),
	} {
		if got != nil {
			t.Fatalf("%s got %#v, want nil", name, got)
		}
	}
}

func TestColumnEquivalentNormalizesDefaults(t *testing.T) {
	e := &Emitter{}

	base := &model.ColumnSchema{
		Name: "status", ColumnType: "text", IsNullable: "YES", ColumnDefault: strPtr("'x'::text"),
	}
	same := &model.ColumnSchema{
		Name: "status", ColumnType: "text", IsNullable: "YES", ColumnDefault: strPtr("'x'"),
	}
	if !e.ColumnEquivalent(base, same) {
		t.Fatalf("'x'::text 与 'x' 应视为等价")
	}

	nowDefault := &model.ColumnSchema{
		Name: "created_at", ColumnType: "timestamp with time zone", IsNullable: "NO",
		ColumnDefault: strPtr("now()"),
	}
	currentDefault := &model.ColumnSchema{
		Name: "created_at", ColumnType: "timestamp with time zone", IsNullable: "NO",
		ColumnDefault: strPtr("CURRENT_TIMESTAMP"),
	}
	if !e.ColumnEquivalent(nowDefault, currentDefault) {
		t.Fatalf("now() 与 CURRENT_TIMESTAMP 应视为等价")
	}

	changed := &model.ColumnSchema{
		Name: "status", ColumnType: "text", IsNullable: "YES", ColumnDefault: strPtr("'y'"),
	}
	if e.ColumnEquivalent(base, changed) {
		t.Fatalf("不同默认值不应视为等价")
	}
}

func TestIndexEquivalent(t *testing.T) {
	e := &Emitter{}

	a := &model.IndexSchema{
		Name: "idx", NonUnique: true, Method: "btree",
		Columns:        []model.IndexColumn{{Name: "a", SeqInIndex: 1}, {Name: "b", SeqInIndex: 2}},
		IncludeColumns: []string{"c"},
		Filter:         "a > 0",
	}
	b := &model.IndexSchema{
		Name: "other_name", NonUnique: true, IndexType: "BTREE",
		Columns:        []model.IndexColumn{{Name: "a", SeqInIndex: 1}, {Name: "b", SeqInIndex: 2}},
		IncludeColumns: []string{"c"},
		Filter:         "a > 0 ",
	}
	if !e.IndexEquivalent(a, b) {
		t.Fatalf("等价索引判断失败")
	}

	b.Columns = []model.IndexColumn{{Name: "a", SeqInIndex: 1}, {Name: "d", SeqInIndex: 2}}
	if e.IndexEquivalent(a, b) {
		t.Fatalf("列不同不应视为等价")
	}
}
