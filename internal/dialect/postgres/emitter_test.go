func TestQuoteAndValue(t *testing.T) {
	e := &Emitter{}

	tests := []struct {
		name string
		got  string
		want string
	}{
		{"标识符双引号", e.QuoteIdentifier(`we"ird`), `"we""ird"`},
		{"限定表名", e.QualifyTable("public", "users"), `"public"."users"`},
		{"空模式限定表名", e.QualifyTable("", "users"), `"users"`},
		{"字符串字面量", e.QuoteStringLiteral("O'Reilly"), `'O''Reilly'`},
		{"NULL", e.FormatValue(nil), "NULL"},
		{"TRUE", e.FormatValue(true), "TRUE"},
		{"FALSE", e.FormatValue(false), "FALSE"},
		{"json.Number 原样输出", e.FormatValue(json.Number("42.5")), "42.5"},
		{"字符串", e.FormatValue("hello"), "'hello'"},
		{"bytea 十六进制", e.FormatValue([]byte{0xde, 0xad}), `'\xdead'::bytea`},
		{"整数", e.FormatValue(42), "42"},
		{"浮点数", e.FormatValue(1.5), "1.5"},
		{
			"时间戳",
			e.FormatValue(time.Date(2024, 1, 2, 3, 4, 5, 0, time.UTC)),
			"'2024-01-02 03:04:05+00:00'",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if tt.got != tt.want {
				t.Fatalf("got %q, want %q", tt.got, tt.want)
			}
		})
	}
}

func TestFormatColumnSpec(t *testing.T) {
	e := &Emitter{}

	tests := []struct {
		name string
		col  *model.ColumnSchema
		want string
	}{
		{
			name: "identity ALWAYS",
			col: &model.ColumnSchema{
				Name: "id", ColumnType: "integer", IsNullable: "NO",
				IsIdentity: true, IdentityGeneration: "ALWAYS",
			},
			want: `"id" integer GENERATED ALWAYS AS IDENTITY NOT NULL`,
		},
		{
			name: "identity BY DEFAULT",
			col: &model.ColumnSchema{
				Name: "id", ColumnType: "bigint", IsNullable: "NO",
				IsIdentity: true, IdentityGeneration: "BY DEFAULT",
			},
			want: `"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		},
		{
			name: "生成列",
			col: &model.ColumnSchema{
				Name: "total", ColumnType: "numeric(10,2)", IsNullable: "YES",
				IsGenerated: true, GenerationExpression: "price * qty",
			},
			want: `"total" numeric(10,2) GENERATED ALWAYS AS (price * qty) STORED`,
		},
		{
			name: "默认值原样输出",
			col: &model.ColumnSchema{
				Name: "created_at", ColumnType: "timestamp with time zone",
				IsNullable: "NO", ColumnDefault: strPtr("now()"),
			},
			want: `"created_at" timestamp with time zone DEFAULT now() NOT NULL`,
		},
		{
			name: "排序规则",
			col: &model.ColumnSchema{
				Name: "name", ColumnType: "text", IsNullable: "YES",
				CollationName: "C",
			},
			want: `"name" text COLLATE "C"`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := e.FormatColumnSpec(tt.col); got != tt.want {
				t.Fatalf("got %q, want %q", got, tt.want)
			}
		})
	}
}

func TestEmitterStatements(t *testing.T) {
	e := &Emitter{}
	table := testTable()

	fromCol := &model.ColumnSchema{
		Name: "name", ColumnType: "character varying(50)", IsNullable: "YES", Comment: "old",
	}
	toCol := &model.ColumnSchema{
		Name: "name", ColumnType: "character varying(100)", IsNullable: "NO",
		ColumnDefault: strPtr("'x'::text"), Comment: "new",
	}

	indexTable := &model.TableSchema{
		Name: "users", Schema: "public",
		PrimaryKey: &model.PrimaryKeySchema{Name: "users_pkey", Columns: []string{"id"}},
	}

	tests := []struct {
		name string
		got  []string
		want []string
	}{
		{
			name: "新增字段",
			got: e.AddColumn(table, &model.ColumnSchema{
				Name: "age", ColumnType: "integer", IsNullable: "NO",
			}),
			want: []string{`ALTER TABLE "public"."users" ADD COLUMN "age" integer NOT NULL;`},
		},
		{
			name: "新增字段并写注释",
			got: e.AddColumn(table, &model.ColumnSchema{
				Name: "age", ColumnType: "integer", IsNullable: "YES", Comment: "年龄",
			}),
			want: []string{
				`ALTER TABLE "public"."users" ADD COLUMN "age" integer;`,
				`COMMENT ON COLUMN "public"."users"."age" IS '年龄';`,
			},
		},
		{
			name: "删除字段",
			got:  e.DropColumn(table, table.Columns[1]),
			want: []string{`ALTER TABLE "public"."users" DROP COLUMN "name";`},
		},
		{
			name: "修改字段",
			got:  e.ModifyColumn(table, fromCol, toCol),
			want: []string{
				`ALTER TABLE "public"."users" ALTER COLUMN "name" TYPE character varying(100) USING "name"::character varying(100);`,
				`ALTER TABLE "public"."users" ALTER COLUMN "name" SET NOT NULL;`,
				`ALTER TABLE "public"."users" ALTER COLUMN "name" SET DEFAULT 'x'::text;`,
				`COMMENT ON COLUMN "public"."users"."name" IS 'new';`,
			},
		},
		{
			name: "添加 identity",
			got: e.ModifyColumn(table,
				&model.ColumnSchema{Name: "id", ColumnType: "integer", IsNullable: "NO"},
				&model.ColumnSchema{Name: "id", ColumnType: "integer", IsNullable: "NO", IsIdentity: true, IdentityGeneration: "ALWAYS"}),
			want: []string{
				`ALTER TABLE "public"."users" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY;`,
			},
		},
		{
			name: "删除默认值",
			got: e.ModifyColumn(table,
				&model.ColumnSchema{Name: "name", ColumnType: "text", IsNullable: "YES", ColumnDefault: strPtr("'x'::text")},
				&model.ColumnSchema{Name: "name", ColumnType: "text", IsNullable: "YES"}),
			want: []string{
				`ALTER TABLE "public"."users" ALTER COLUMN "name" DROP DEFAULT;`,
			},
		},
		{
			name: "新增主键",
			got:  e.AddPrimaryKey(indexTable),
			want: []string{`ALTER TABLE "public"."users" ADD CONSTRAINT "users_pkey" PRIMARY KEY ("id");`},
		},
		{
			name: "删除主键",
			got:  e.DropPrimaryKey(indexTable),
			want: []string{`ALTER TABLE "public"."users" DROP CONSTRAINT "users_pkey";`},
		},
		{
			name: "新增普通索引",
			got: e.AddIndex(indexTable, &model.IndexSchema{
				Name: "idx_users_email", NonUnique: true, Method: "btree",
				Columns:        []model.IndexColumn{{Name: "email", SeqInIndex: 1}},
				IncludeColumns: []string{"name"},
				Filter:         "email IS NOT NULL",
			}),
			want: []string{`CREATE INDEX "idx_users_email" ON "public"."users" USING "btree" ("email") INCLUDE ("name") WHERE email IS NOT NULL;`},
		},
		{
			name: "删除普通索引",
			got:  e.DropIndex(indexTable, &model.IndexSchema{Name: "idx_users_email", NonUnique: true}),
			want: []string{`DROP INDEX "public"."idx_users_email";`},
		},
		{
			name: "新增唯一约束索引",
			got: e.AddIndex(indexTable, &model.IndexSchema{
				Name: "uq_users_email", NonUnique: false, Method: "btree",
				Columns:      []model.IndexColumn{{Name: "email", SeqInIndex: 1}},
				IsConstraint: true, ConstraintType: "UNIQUE",
			}),
			want: []string{`ALTER TABLE "public"."users" ADD CONSTRAINT "uq_users_email" UNIQUE ("email");`},
		},
		{
			name: "删除唯一约束索引",
			got: e.DropIndex(indexTable, &model.IndexSchema{
				Name: "uq_users_email", NonUnique: false, IsConstraint: true,
			}),
			want: []string{`ALTER TABLE "public"."users" DROP CONSTRAINT "uq_users_email";`},
		},
		{
			name: "表注释",
			got:  e.SetTableComment(table, "用户表"),
			want: []string{`COMMENT ON TABLE "public"."users" IS '用户表';`},
		},
		{
			name: "清空表注释",
			got:  e.SetTableComment(table, ""),
			want: []string{`COMMENT ON TABLE "public"."users" IS NULL;`},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if !reflect.DeepEqual(tt.got, tt.want) {
				t.Fatalf("got %#v, want %#v", tt.got, tt.want)
			}
		})
	}
}

func TestCreateTable(t *testing.T) {
	e := &Emitter{}
	table := &model.TableSchema{
		Name:    "users",
		Schema:  "public",
		Comment: "用户表",
		Columns: []*model.ColumnSchema{
			{Name: "id", ColumnType: "integer", IsNullable: "NO", IsIdentity: true, IdentityGeneration: "ALWAYS"},
			{Name: "email", ColumnType: "character varying(255)", IsNullable: "NO", Comment: "邮箱"},
		},
		PrimaryKey: &model.PrimaryKeySchema{Name: "users_pkey", Columns: []string{"id"}},
		Indexes: []*model.IndexSchema{
			{
				Name: "idx_users_email", NonUnique: true, Method: "btree",
				Columns: []model.IndexColumn{{Name: "email", SeqInIndex: 1}},
			},
		},
	}

	want := []string{
		"CREATE TABLE \"public\".\"users\" (\n" +
			"  \"id\" integer GENERATED ALWAYS AS IDENTITY NOT NULL,\n" +
			"  \"email\" character varying(255) NOT NULL,\n" +
			"  CONSTRAINT \"users_pkey\" PRIMARY KEY (\"id\")\n" +
			");",
		`CREATE INDEX "idx_users_email" ON "public"."users" USING "btree" ("email");`,
		`COMMENT ON TABLE "public"."users" IS '用户表';`,
		`COMMENT ON COLUMN "public"."users"."email" IS '邮箱';`,
	}

	got := e.CreateTable(table)
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %#v, want %#v", got, want)
	}
}

